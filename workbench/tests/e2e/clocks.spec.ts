import { expect, test } from '@playwright/test'

test('顶栏同时显示北京和洛杉矶当地日期时间，跨日及夏令时按当地时区换算', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-07-01T06:59:00Z') })
  await page.goto('/')
  const bar = page.getByRole('banner')
  const times = bar.getByRole('region', { name: '市场时钟' }).locator('time')
  await expect(bar.getByText('美国站', { exact: true })).toBeVisible()
  await expect(bar.getByText('美国市场')).toHaveCount(0)
  await expect(bar.getByTitle('洛杉矶 · America/Los_Angeles')).toContainText('美西时间')
  await expect(times.nth(0)).toHaveText('07/01 14:59')
  await expect(times.nth(1)).toHaveText('06/30 23:59')
  await page.clock.fastForward(60_000)
  await expect(times.nth(1)).toHaveText('07/01 00:00')
  await page.clock.setSystemTime(new Date('2026-11-01T08:59:00Z'))
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
  await expect(times.nth(1)).toHaveText('11/01 01:59')
  await page.clock.fastForward(60_000)
  await expect(times.nth(1)).toHaveText('11/01 01:00')
  await page.clock.setSystemTime(new Date('2026-12-01T07:59:00Z'))
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
  await expect(times.nth(0)).toHaveText('12/01 15:59')
  await expect(times.nth(1)).toHaveText('11/30 23:59')
  await page.setViewportSize({ width: 360, height: 800 })
  for (const time of await times.all()) await expect(time).toBeInViewport()
  expect(await bar.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true)
})
