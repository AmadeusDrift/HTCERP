import { expect, test } from '@playwright/test'
test('运营从巡检进入词库查别名、新增风险词并用新上架标题验证', async ({ page }) => {
  await page.goto('/title-audit')
  await expect(page.getByRole('heading', { name: '文字侵权检测', exact: true })).toBeVisible()
  await expect(page.getByLabel('亚马逊处置')).toBeVisible()
  await page.getByRole('button', { name: '词库', exact: true }).click()
  await page.getByLabel('查词或关联表达').fill('Spiderman')
  const match = page
    .locator('article')
    .filter({ has: page.getByRole('button', { name: '查看 Marvel 关联词' }) })
    .first()
  await expect(match).toContainText('Spider-Man')
  await match.getByRole('button').click()
  await expect(page.getByRole('button', { name: 'Marvel ×' })).toBeVisible()
  await page.getByText('新增运营风险词', { exact: true }).click()
  const word = 'AuditBrand' + Date.now()
  await page.getByLabel('标准名称').fill(word)
  await page.getByLabel('所属家族').fill('测试家族')
  await page.getByLabel('别名（用逗号分隔）').fill(word + 'Alias')
  await page.getByLabel('重点提醒的原因').fill('内部标题测试')
  await page.getByRole('button', { name: '保存风险词' }).click()
  await expect(page.getByRole('status')).toContainText('已加入')
  await page.getByRole('button', { name: '新上架标题自查' }).click()
  await page.getByLabel('美国站英文标题').fill(word + 'Alias Mug')
  await page.getByRole('button', { name: '检查标题' }).click()
  await expect(page.getByRole('heading', { name: '重点提醒' })).toBeVisible()
  await expect(page.locator('mark').filter({ hasText: word + 'Alias' })).toHaveCount(1)
})
